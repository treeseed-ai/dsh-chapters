#!/usr/bin/env bash
# Docker entrypoint for dsh-chapters-dev Web UI service
# Generates settings.yaml from environment variables and starts DSH web.

set -euo pipefail

PROFILE_DIR="$DSH_HOME/profiles/web"

# ── Defaults ───────────────────────────────────────────────────────────────────
LLM_BASE_URL="${LLM_BASE_URL:-http://vllm:8080/v1}"
LLM_MODEL="${LLM_MODEL:-qwen3-4b-instruct}"
LLM_CONTEXT_WINDOW="${LLM_CONTEXT_WINDOW:-32768}"
LLM_MAX_TOKENS="${LLM_MAX_TOKENS:-15000}"
LOCAL_API_KEY="${LOCAL_API_KEY:-sk-local}"
SYSTEMONE_BASE_URL="${SYSTEMONE_BASE_URL:-http://vllm:8080/v1}"
SYSTEMONE_MODEL="${SYSTEMONE_MODEL:-qwen3-4b-systemone}"
QWEN_TOKEN_PLAN_API_KEY="${QWEN_TOKEN_PLAN_API_KEY:-}"
TINYFISH_API_KEY="${TINYFISH_API_KEY:-}"
DSH_PORT="${DSH_PORT:-3080}"
DSH_HOST="${DSH_HOST:-0.0.0.0}"

# ── Generate settings.yaml ────────────────────────────────────────────────────
echo "[entrypoint] Generating settings for model=$LLM_MODEL window=$LLM_CONTEXT_WINDOW..."

cat > "$PROFILE_DIR/settings.yaml" <<SETTINGS
# Auto-generated by docker-entrypoint.sh at $(date -u +%Y-%m-%dT%H:%M:%SZ)
llm-pi-ai:
  providers:
    # Local vLLM provider (Qwen3-4B-AWQ)
    local:
      displayName: Local vLLM
      api: openai-completions
      baseURL: ${LLM_BASE_URL}
      models:
        - id: ${LLM_MODEL}
          name: "${LLM_MODEL} (local vLLM)"
          contextWindow: ${LLM_CONTEXT_WINDOW}
          maxTokens: ${LLM_MAX_TOKENS}
          reasoningEfforts:
            off:
            low: low
            medium: medium
            high: high
            xhigh: xhigh
        - id: ${SYSTEMONE_MODEL}
          name: "${SYSTEMONE_MODEL} (systemone decision)"
          contextWindow: ${LLM_CONTEXT_WINDOW}
          maxTokens: 4096
      apiKeyEnv: LOCAL_API_KEY
      streamIdleTimeoutMs: 3600000
      timeoutMs: 3600000
      reasoning: medium
      retryPolicy:
        mode: normal
        maxRetries: 0
      compat:
        supportsDeveloperRole: false
    # Alibaba Qwen Token Plan marketplace (optional — needs API key)
    qwen-token-plan:
      models:
        - id: deepseek-v4-pro
          name: DeepSeek V4 Pro
          contextWindow: 1000000
          maxTokens: 384000
          input: [text]
        - id: deepseek-v4.1-flash
          name: DeepSeek V4.1 Flash
          contextWindow: 1000000
          maxTokens: 384000
          input: [text, image]
        - id: glm-5.3
          name: GLM-5.3
          contextWindow: 1000000
          maxTokens: 131072
          input: [text]
        - id: kimi-k2.6
          name: Kimi K2.6
          contextWindow: 262144
          maxTokens: 262144
          input: [text, image]
        - id: kimi-k2.7-code
          name: Kimi K2.7 Code
          contextWindow: 262144
          maxTokens: 262144
          input: [text, image]
        - id: MiniMax-M2.5
          name: MiniMax-M2.5
          contextWindow: 196608
          maxTokens: 32768
          input: [text]
        - id: qwen3.8-flash
          name: Qwen3.8 Flash
          contextWindow: 1000000
          maxTokens: 131072
          input: [text, image]
        - id: qwen3.8-max
          name: Qwen3.8 Max
          contextWindow: 1000000
          maxTokens: 131072
          input: [text, image]
      apiKeyEnv: QWEN_TOKEN_PLAN_API_KEY

agent-default-model:
  provider: local
  model: ${LLM_MODEL}
  reasoningEffort: medium

agent-presets:
  default: chapters

ui-onboarding:
  welcomeNoticeVersion: 2026-08-13.1
SETTINGS

export LOCAL_API_KEY
export QWEN_TOKEN_PLAN_API_KEY
export TINYFISH_API_KEY

# ── Start DSH Web UI ──────────────────────────────────────────────────────────
echo "[entrypoint] Starting DSH Web UI on ${DSH_HOST}:${DSH_PORT}..."
echo "[entrypoint] Profile: web"
echo "[entrypoint] LLM: $LLM_BASE_URL ($LLM_MODEL)"
echo "[entrypoint] SystemOne: $SYSTEMONE_BASE_URL ($SYSTEMONE_MODEL)"
echo "[entrypoint] Token plan: ${QWEN_TOKEN_PLAN_API_KEY:+configured}${QWEN_TOKEN_PLAN_API_KEY:-not set}"

exec dsh --profile web web \
  --host "$DSH_HOST" \
  --port "$DSH_PORT"
