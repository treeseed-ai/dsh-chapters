#!/usr/bin/env node
/**
 * Write a PROVENANCE.md into every tape project directory (#56).
 *
 * Why this is code and not a hand-written file: the runner clears each project directory before it
 * records (`rm -rf tests/fixtures/model-tape/<proj>`), so any hand-authored provenance is destroyed
 * on every re-anchor. Measured on this branch — the re-anchor commit deleted `plans/PROVENANCE.md`
 * and `prompt/PROVENANCE.md`, the two records that say those legs were distilled from the SCRIPTED
 * upstream and not from a live model. A claim about what a tape means, erased by the act of
 * re-making the tape, is worse than never having written it.
 *
 * Usage: node scripts/write-provenance.mjs [--verdicts var/reattempt.log]
 */
import fs from 'node:fs'
import path from 'node:path'
import { RIG_PINS } from '../tests/e2e/rig-pins.ts'
import { corpusAnchor } from './corpus-anchor.mjs'

const ROOT = path.resolve(import.meta.dirname, '..')
const argv = process.argv.slice(2)
const verdictArg = argv.includes('--verdicts') ? argv[argv.indexOf('--verdicts') + 1] : null
// `--project <name> --verdict "exit=0 tapeEntries=7"`: the runner calls this right after a leg,
// when it knows the verdict and nothing else does. Without it a single-project run would rewrite
// every project's provenance with a stale date.
const onlyProject = argv.includes('--project') ? argv[argv.indexOf('--project') + 1] : null
const inlineVerdict = argv.includes('--verdict') ? argv[argv.indexOf('--verdict') + 1] : null
const anchor = corpusAnchor(ROOT)
const verdicts = verdictArg && fs.existsSync(path.join(ROOT, verdictArg))
  ? fs.readFileSync(path.join(ROOT, verdictArg), 'utf8')
  : ''
const today = new Date().toISOString().slice(0, 10)
const STUB = new Set(['plans', 'prompt'])

let written = 0
for (const [proj, pin] of Object.entries(RIG_PINS)) {
  // null means ALL projects here; comparing against undefined made the default mode write
  // NOTHING and still report success — the provenance row caught it on the run after it landed.
  if (onlyProject !== null && proj !== onlyProject) continue
  const dir = path.join(ROOT, 'tests', 'fixtures', 'model-tape', proj)
  if (!fs.existsSync(dir)) { console.error(`skip ${proj}: no tape directory`); continue }
  const entries = fs.readdirSync(dir).filter((x) => x.endsWith('.json')).length
  // The LAST verdict for a project is the truth, not the first: a pass can be followed by a red
  // attempt that was interrupted, and the file I read tonight showed `heavy` as exit 1 with a later
  // exit 0 line underneath. Reading the first match writes a stale claim into the record that
  // exists to prevent stale claims.
  const all = [...verdicts.matchAll(new RegExp(`--- ${proj}: exit=(\\d+) tapeEntries=(\\d+)`, 'g'))]
  const vm = inlineVerdict !== null
    ? /exit=(\d+) tapeEntries=(\d+)/.exec(inlineVerdict)
    : (all.length > 0 ? all[all.length - 1] : null)
  const regime = `port ${String(pin.port)}, threshold ${pin.threshold}`
    + (pin.floor !== undefined ? `, arrival floor ${pin.floor}` : ', arrival floor (realm default)')
    + (pin.enrich ? ', enrichment enabled' : '')
    + (pin.noAuxModel ? ', auxiliary model calls off' : '')
    + (pin.promptModel ? ', prompt-ghost model defined' : '')
  const upstream = STUB.has(proj)
    ? 'SCRIPTED stub (`tests/e2e/stub-model.ts`) — deliberately. This leg must NOT freeze one model\'s decision to plan / to suggest a constant only the stub mints.'
    : 'hosted endpoint (`token-plan…`, model `qwen3.8-flash`)'
  const body = `# Tape provenance — \`${proj}\` project

**Distilled ${today}** against host \`${anchor.pinned}\` (\`dev/dsh-host-lock\`).
Last recorded verdict: ${vm ? `exit ${vm[1]}, ${vm[2]} tape entries` : 'see `var/distill/` logs'}.

- **Regime as recorded (from \`tests/e2e/rig-pins.ts\`, the single authority):** ${regime}.
  The boot and every worker read those pins; replay boots the SAME regime, or the tape means
  something else than it recorded (#56 — divergent pins were the reason replay MISSed).
- **Upstream:** ${upstream}
- **Window enforcement:** the rig refuses any chat request whose whole body exceeds
  \`E2E_WINDOW_TOKENS\` (default 32000) in record AND replay, and never records a refusal.
- **Composer behavior:** one instruction ⇒ one durable \`user/message\` (#81/#84 — the guard decides
  from the durable log, waits out the flush, and matches the full instruction).

This file is GENERATED by \`scripts/write-provenance.mjs\` (it is rewritten on every re-anchor,
because the runner clears the project directory). Keep durable reasoning in \`docs/\`, not here.
`
  fs.writeFileSync(path.join(dir, 'PROVENANCE.md'), body)
  written += 1
}
console.log(`provenance written for ${written} project(s); host ${anchor.pinned}`)
