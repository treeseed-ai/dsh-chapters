/**
 * Provenance must exist as a file, per project, or the chain's meaning is folklore (#56).
 *
 * What made this a rule rather than a nicety: my own re-anchor commit deleted
 * `plans/PROVENANCE.md` and `prompt/PROVENANCE.md` — the records saying those legs are distilled
 * from the SCRIPTED stub, which is exactly the fact a reader needs to interpret an entry that no
 * live model would produce. The runner clears each project dir before recording, so anything
 * hand-authored there is destroyed on every re-anchor. Hence: generated, and asserted.
 */
import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'

const ROOT = path.resolve(import.meta.dirname, '..', '..')
const TAPE = path.join(ROOT, 'tests', 'fixtures', 'model-tape')
const PROJECTS = ['suite', 'heavy', 'arrival', 'enrich', 'fanout', 'rules', 'fork', 'plans', 'prompt']

test('every tape project carries a PROVENANCE.md naming the host it was distilled against', () => {
  const missing = PROJECTS.filter((p) => !fs.existsSync(path.join(TAPE, p, 'PROVENANCE.md')))
  assert.deepEqual(missing, [],
    `these projects have no provenance record: ${missing.join(', ')} — without it a tape's regime is folklore`)
  for (const p of PROJECTS) {
    const body = fs.readFileSync(path.join(TAPE, p, 'PROVENANCE.md'), 'utf8')
    assert.match(body, /0\.2\.0-rc\.2|dev\/dsh-host-lock/, `${p}: must name the host the tape was distilled against`)
    assert.match(body, /rig-pins\.ts/, `${p}: must point at the single pin authority, not restate numbers freehand`)
    assert.match(body, /GENERATED by/, `${p}: provenance is generated, because the runner clears the directory`)
  }
})

test('the runner regenerates provenance instead of letting its own clear destroy it', () => {
  const script = fs.readFileSync(path.join(ROOT, 'scripts', 'distill-tapes.sh'), 'utf8')
  assert.match(script, /write-provenance/,
    'a leg that re-records must leave its provenance behind, or the corpus loses the fact it documents')
})
