/**
 * REASONING-BLIND (#90, measured 2026-10-24). A replay stalled with `divergeAt=msg2` where BOTH sides
 * were `{"role":"assistant","content":null,"reasoning_content":"…"}` and only the reasoning prose
 * differed:
 *
 *   got      "The user asks: which file defines the chapter composer …"
 *   expected "Also check primaryMatch and merge decision around line 150-180 …"
 *
 * Reasoning text is model-internal volatility: it is not what the plugin claims, not what the user
 * sees as an answer, and it is regenerated by the harness's own re-entry of the served bytes. Treating
 * it as conversation identity made the FIRST turn of the journey unmatchable, so no answer was served,
 * no assistant row rendered, and the fork door never appeared — the 25-minute hang, from a text
 * difference nobody can control. Same class as HOSTPORT/SESSIONID/WORKSPACE-BLIND.
 */
test('assistant reasoning prose cannot break a tape match', () => {
  const a = normalizeSingle({ role: 'assistant', content: null, reasoning_content: 'The user asks: which file defines the composer rule' })
  const b = normalizeSingle({ role: 'assistant', content: null, reasoning_content: 'Also check primaryMatch and merge decision around line 150' })
  assert.equal(a, b, 'two assistant turns with the same visible content must normalize identically')
  assert.match(a, /reasoning_content/, 'and the FIELD is kept, so a reasoning-bearing turn is still distinguishable from one without')
  const c = normalizeSingle({ role: 'assistant', content: 'the answer', reasoning_content: 'x' })
  const d = normalizeSingle({ role: 'assistant', content: 'the answer' })
  assert.notEqual(c, d, 'visible content still matters, and its absence is a different conversation')
})

/**
 * The fold is only worth having if it lands on BOTH sides. `loadTape` deliberately runs just
 * `substituteAll` on stored string prefixes (re-running `normalize` double-stringifies them — the S0
 * lesson), so a fold living only in `normalize` would have folded the incoming side and left the tape's
 * own reasoning prose untouched: every reasoning-bearing turn becomes UNMATCHABLE, and the rig gets
 * WORSE at the thing it was just fixed for.
 */
test('stored tape prefixes get the same reasoning fold as the incoming side (#90)', async () => {
  const { foldReasoning, normalizeSingle } = await import('../../tests/e2e/model-proxy.ts')
  const stored = '{"role":"assistant","content":null,"reasoning_content":"Also check primaryMatch and merge decision around line 150"}'
  const incoming = normalizeSingle({ role: 'assistant', content: null, reasoning_content: 'The user asks: which file defines the composer rule' })
  assert.equal(foldReasoning(stored), incoming, 'a pre-blind tape string must fold to exactly what the live side produces')
  assert.ok(foldReasoning(stored).includes('⟦REASONING⟧'), 'the prose is gone')
  assert.ok(foldReasoning(stored).includes('reasoning_content'), 'the field is not deleted')
  assert.equal(foldReasoning('{"role":"user","content":"no reasoning here"}'), '{"role":"user","content":"no reasoning here"}',
    'and a message without reasoning is byte-identical — the fold is not a global rewrite')
})

/**
 * Message INDEX is part of a conversation's identity, so the two sides of a match must agree about
 * what a message even is (#90, measured 2026-10-24: a replay missed with `divergeAt=msg4` because the
 * stored prefix held `''` items at 3 and 4 — `loadTape` filters those away, so a 9-message stored
 * prefix became a 7-message candidate, and every position after the first empty one silently shifted
 * against the incoming array). Dropping on one side only is not normalization, it is desynchronization.
 */
test('empty-normalizing messages are treated identically on both sides of a match (#90)', async () => {
  const { normalizeSingle } = await import('../../tests/e2e/model-proxy.ts')
  const fs = await import('node:fs')
  const path = await import('node:path')
  const root = path.resolve(import.meta.dirname, '..', '..')
  const proxy = fs.readFileSync(path.join(root, 'tests', 'e2e', 'model-proxy.ts'), 'utf8')
  // findReplay must not drop empties from the incoming side while loadTape keeps them stored (or the
  // reverse): one policy, applied to both.
  const replay = proxy.slice(proxy.indexOf('function findReplay'), proxy.indexOf('export function normalizeSingle'))
  const load = proxy.slice(proxy.indexOf('function loadTape'), proxy.indexOf('function findReplay'))
  const incomingDrops = /\.filter\(\(x\) => x !== ''\)/.test(replay)
  const storedDrops = /\.filter\(\(x\) => x !== ''\)/.test(load)
  assert.equal(incomingDrops, storedDrops,
    `both sides must apply the same empties policy (incoming drops=${String(incomingDrops)}, stored drops=${String(storedDrops)})`)
  assert.equal(typeof normalizeSingle(''), 'string', 'and an empty message is still a message, not a hole in the array')
})

/**
 * ELAPSED-BLIND (#56, measured 2026-10-26 at msg3 of the suite journey).
 *
 * The host injects a time-context message every turn whose text carries a wall-clock fact:
 * `Elapsed since the preceding model-visible message: 12m 4s.` — and `…: unavailable.` when the
 * span is unknown. A record run answers from a live model minutes apart; a replay run answers from the
 * tape in seconds. So the same conversation produces DIFFERENT request arrays, `findReplay` finds no
 * candidate of that length at all (`storedCandidates: []` in the E2E_TAPE_DIFF dump), strict replay
 * refuses, no assistant message renders, and the leg dies at the fork door after 25 minutes — the same
 * ending as four unrelated causes today, from a fifth. The date inside that line was already masked;
 * the duration was not, and the duration is the volatile half.
 */
test('the injected time-context snapshot cannot break a tape match (elapsed duration)', () => {
  const slow = normalizeSingle({ role: 'user', content: 'Time sampled while preparing turn 1, step 1: 2026-10-26T21:00:00-04:00[America/New_York] Browser time zone for this request: America/New_York. Interpret otherwise-unqualified dates and times in this zone. Elapsed since the preceding model-visible message: 12m 4s.' })
  const fast = normalizeSingle({ role: 'user', content: 'Time sampled while preparing turn 1, step 1: 2026-10-26T21:20:00-04:00[America/New_York] Browser time zone for this request: America/New_York. Interpret otherwise-unqualified dates and times in this zone. Elapsed since the preceding model-visible message: unavailable.' })
  assert.equal(slow, fast, `two spacings of the same injected snapshot must be one identity: …${String(slow).slice(-60)}`)
  // The blind must be narrow: real conversation text that merely mentions an elapsed time is signal,
  // and masking it would let a genuine prompt change replay against a stale answer (#69's lesson).
  const human = normalizeSingle({ role: 'user', content: 'The build took 12m 4s. Elapsed since the preceding model-visible message is a red herring here.' })
  assert.ok(!human.includes('<ELAPSED>'), 'prose about elapsed time is NOT folded')
  assert.notEqual(human, slow)

  // The exact shapes seen in one hour of logs, recorded with and without the sentence's final period. The
  // first version of my fold consumed the period only sometimes, which left a ONE-CHARACTER difference
  // between an incoming request and the tape recorded minutes earlier — enough to fail the match, enough
  // to spend 25 minutes at a fork door. Variants are the unit of this kind of bug.
  const t = (elapsed: string): string => normalizeSingle({ role: 'user', content: `Time sampled while preparing turn 1, step 1: 2026-10-26T21:00:00-04:00[America/New_York] Browser time zone for this request: America/New_York. Interpret otherwise-unqualified dates and times in this zone. ${elapsed}` })
  const forms = [
    'Elapsed since the preceding model-visible message: 12m 4s.',
    'Elapsed since the preceding model-visible message: 12m 4s',
    'Elapsed since the preceding model-visible message: unavailable.',
    'Elapsed since the preceding model-visible message: unavailable',
    'Elapsed since the preceding step context: 11m 36s.',
  ].map(t)
  // Two LINES, not one: the host injects `…preceding model-visible message…` in one snapshot position and
  // `…preceding step context…` in another, and they are different sentences in different messages, so they
  // are not required to fold to the same token. What MUST hold is that each line folds every VALUE shape to
  // one identity — the assertion I wrote first was overstated, and the failing row is what caught that.
  const messageForms = forms.slice(0, 4)
  assert.ok(messageForms.every((f) => f === messageForms[0]),
    `all elapsed values of the model-visible line must fold together; got ${new Set(messageForms).size} distinct`)
  assert.ok(forms[4].includes('step context: <ELAPSED>'), 'the step-context line folds its value too')
  assert.ok(!forms[4].includes('11m'), 'and the duration itself is gone')
})

