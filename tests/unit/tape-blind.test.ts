import test from 'node:test'
import assert from 'node:assert/strict'
import { normalizeSingle } from '../../tests/e2e/model-proxy.ts'


/**
 * REASONING-BLIND (#90, measured 2026-10-24). A replay stalled with `divergeAt=msg2` where BOTH sides
 * were `{"role":"assistant","content":null,"reasoning_content":"…"}` and only the reasoning prose
 * differed:
 *
 *   got      "The user asks: which file defines the chapter composer …"
 *   expected "Also check primaryMatch and merge decision around line 150-180 …"
 *
 * Reasoning text is model-internal volatility: it is not what the plugin claims, not what the user
 * sees as an answer, and it is regenerated by the harness's own re-entry of the served bytes. Treating
 * it as conversation identity made the FIRST turn of the journey unmatchable, so no answer was served,
 * no assistant row rendered, and the fork door never appeared — the 25-minute hang, from a text
 * difference nobody can control. Same class as HOSTPORT/SESSIONID/WORKSPACE-BLIND.
 */
test('assistant reasoning prose cannot break a tape match', () => {
  const a = normalizeSingle({ role: 'assistant', content: null, reasoning_content: 'The user asks: which file defines the composer rule' })
  const b = normalizeSingle({ role: 'assistant', content: null, reasoning_content: 'Also check primaryMatch and merge decision around line 150' })
  assert.equal(a, b, 'two assistant turns with the same visible content must normalize identically')
  assert.match(a, /reasoning_content/, 'and the FIELD is kept, so a reasoning-bearing turn is still distinguishable from one without')
  const c = normalizeSingle({ role: 'assistant', content: 'the answer', reasoning_content: 'x' })
  const d = normalizeSingle({ role: 'assistant', content: 'the answer' })
  assert.notEqual(c, d, 'visible content still matters, and its absence is a different conversation')
})
